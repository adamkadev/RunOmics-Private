// Green light is good news; caution and hold back both ask for care (v4.17).
// Building is neither: the normal day of a block, in neutral ink, so amber
// keeps meaning something.
const VERDICT_TONE: Record<ReadinessTone, VerdictTone> = {
  go: 'pos',
  build: 'neutral',
  caution: 'warn',
  hold: 'warn',
}

interface Props {
  status: TrainingStatus | null
  plannedWorkout: HeroWorkoutView | null
  todayActivity: ActivitySummary | null
  aiVerdict: Insight | null
  /** The next session on the plan, which a rest day names. */
  nextSession?: NextSession | null
  /** Yesterday's run, when one was run: a hard one is still in the legs today. */
  yesterday?: SessionKind | null
  /** The row above the session tile: today's run once done, or yesterday's run or missed session. */
  lastRun?: LastRun | null
  /** Today's date, for the tile's "Today · Wed, Oct 7". */
  today?: string
}

/**
 * The last run, on one row (design review, Oct 2026): a check in the
 * positive status for a run, a dashed cross in the negative one for a session
 * nobody ran - shape and colour both, never colour alone. A run opens; a
 * missed session opens the plan, read-only.
 */
function LastRunRow({ run }: { run: LastRun }) {
  const missed = run.state === 'missed'
  return (
    <Link href={run.href} data-testid="last-run" data-state={run.state} className="flex min-h-12 items-center gap-3 transition-opacity active:opacity-70">
      <span
        aria-hidden
        className="flex size-8 shrink-0 items-center justify-center rounded-full text-[13px] font-bold"
        style={
          missed
            ? { border: '1.5px dashed var(--neg)', background: 'color-mix(in srgb, var(--neg) 12%, transparent)', color: 'var(--neg)' }
            : { background: 'color-mix(in srgb, var(--pos) 18%, transparent)', color: 'var(--pos)' }
        }
      >
        {missed ? '✕' : <Check size={16} strokeWidth={2.6} />}
      </span>
      <span className="flex min-w-0 flex-1 flex-col gap-0.5">
        <span className="break-words text-sm font-semibold text-pretty text-foreground">{run.title}</span>
        <span className="text-xs leading-snug text-muted-foreground">{run.detail}</span>
      </span>
      <ChevronRight size={16} className="shrink-0 text-subtle" aria-hidden />
    </Link>
  )
}

/**
 * The session to run (design review, Oct 2026): today's before it is run,
 * else the next one, with what it is, its paces and its structure, and the
 * plan a tap away. The plan is generated by the coach: "Open plan" opens it.
 */
function SessionTile({ eyebrow, workout, title }: { eyebrow: string; workout: HeroWorkoutView | null; title: string }) {
  const s = t.dashboard.todayHero
  const detail = workout ? plannedDetail(workout) : null
  return (
    <div data-testid="session-tile" className="flex flex-col gap-3 rounded-2xl bg-[var(--surface-2)] px-3.5 py-3">
      <div className="flex items-center gap-3">
        <span className="flex min-w-0 flex-1 flex-col gap-0.5">
          <span className="text-[11.5px] font-bold uppercase tracking-[0.08em] text-accent-text">{eyebrow}</span>
          <span className="break-words text-[15px] font-semibold text-pretty text-foreground">{title}</span>
          {detail && <span className="text-xs leading-snug text-muted-foreground">{detail}</span>}
        </span>
        <ButtonLink href="/plan" variant="secondary" size="sm" className="hit-44 shrink-0 px-3 font-medium">
          {s.openPlan}
        </ButtonLink>
      </div>
      {workout?.duration && workout.structure && (
        <div data-testid="today-structure-bar">
          <SessionStructureBar
            steps={workout.structure}
            zoneWord={workout.type ? (EFFORT_ZONE_BY_TYPE[workout.type] ?? null) : null}
            zone={workout.type ? sessionZone(workout) : null}
            totalSeconds={workout.duration.seconds}
            bare
          />
        </div>
      )}
    </div>
  )
}

// No race countdown here: the race is the plan's reason, not a daily number,
// and the D-21 chip next to the verdict was noise in the morning read. The
// countdown lives on Plan's race footer and on Goals.
export function TodayHero({ status, plannedWorkout, todayActivity, aiVerdict, nextSession = null, yesterday = null, lastRun = null, today }: Props) {
  if (!status && !plannedWorkout && !todayActivity) return null

  const s = t.dashboard.todayHero
  const readiness = status ? verdictTone(status) : 'go'
  const session = todaySession(plannedWorkout, todayActivity, nextSession)
  // Without a written verdict, one from today's plan, yesterday's run and
  // the next session (v4.17.1): what to do, why, and what it gives.
  const own = status
    ? todayVerdict({
        tone: readiness,
        today: todayPlanOf(session.state, plannedWorkout?.type ?? null),
        yesterday,
        next: nextSession ? { date: nextSession.date, inDays: nextSession.inDays, kind: nextSession.kind } : null,
      })
    : null
  const verdict = aiVerdict ?? own
  const tone = VERDICT_TONE[readiness]
  const eyebrow = s.eyebrowByTone[readiness]

  // The coach's own sentence under its headline; without one, the why and
  // what it gives. Neither repeats the Form / Fitness / Fatigue row below.
  const body: ReactNode = aiVerdict?.body ? (
    <span data-testid="today-body">{aiVerdict.body}</span>
  ) : own ? (
    <span data-testid="today-reason">{own.body}</span>
  ) : null

  // Today's session until it is run, then the next one (design review, Oct 2026).
  const tile =
    session.state === 'planned' && plannedWorkout
      ? { eyebrow: s.tileToday(today ? formatDate(today) : null), workout: plannedWorkout, title: session.title }
      : nextSession
        ? { eyebrow: s.tileNext(formatDate(nextSession.date)), workout: nextSession.workout ?? null, title: nextSession.workout ? workoutSummary({ ...nextSession.workout, structure: nextSession.workout.structure ?? null }).title : nextSession.title }
        : null

  // A plain surface card (v4.17): the verdict's colour is its eyebrow's
  // alone, and nothing tints the card or its border.
  return (
    <section className={cardClass({ padding: 'lg', className: 'flex flex-col gap-4' })} data-testid="today-hero">
      {verdict ? (
        <VerdictBlock tone={tone} eyebrow={eyebrow} headline={verdict.headline} body={body} size="lg" />
      ) : (
        <VerdictEyebrow tone={tone}>{eyebrow}</VerdictEyebrow>
      )}

      <div className="flex flex-col gap-2 border-t border-border pt-2">
        {lastRun && <LastRunRow run={lastRun} />}
        {tile ? (
          <SessionTile eyebrow={tile.eyebrow} workout={tile.workout} title={tile.title} />
        ) : (
          // Nothing to run in the week ahead: the day, and the plan a tap away.
          <div data-testid="session-tile" className="flex items-center gap-3 py-1">
            <span className="flex min-w-0 flex-1 flex-col gap-0.5">
              <span className="text-sm font-semibold text-foreground">{session.title}</span>
              {session.detail && <span className="text-xs leading-snug text-muted-foreground">{session.detail}</span>}
            </span>
            <ButtonLink href="/plan" variant="secondary" size="sm" className="hit-44 shrink-0 px-3 font-medium">
              {s.openPlan}
            </ButtonLink>
          </div>
        )}
      </div>
    </section>
  )
}
