'use client'

import { useEffect, useId, useState } from 'react'
import { createPortal } from 'react-dom'
import Link from 'next/link'
import { ArrowDownRight, ArrowRight, ArrowUpRight, ChevronRight } from 'lucide-react'
import { DELTA_TONE_COLOR } from '@/lib/deltaTone'
import { VerdictEyebrow } from '@/components/ui/Verdict'
import { t } from '@/i18n'
import { useFocusTrap } from '@/lib/useFocusTrap'
import { useScrollLock } from '@/lib/useScrollLock'
import type { Direction, TabRead } from './coachReadTabs'
import type { Trend } from './analyticsView'

/**
 * The arrow follows the number and the colour says what it means (App Fixes,
 * rule 04). Fatigue down 23 is a drop drawn in mint; read off the meaning
 * alone, as it was, the same row pointed up while the number fell.
 *
 * A row with no number of its own keeps the meaning's own arrow, so the
 * sheet never mixes a direction with nothing to point at.
 */
const DIRECTION_ICON: Record<Direction, typeof ArrowRight> = {
  up: ArrowUpRight,
  level: ArrowRight,
  down: ArrowDownRight,
}

const TREND_DIRECTION: Record<Trend, Direction> = { improving: 'up', flat: 'level', declining: 'down' }

const TREND_COLOR: Record<Trend, string> = {
  improving: DELTA_TONE_COLOR.good,
  flat: DELTA_TONE_COLOR.flat,
  declining: DELTA_TONE_COLOR.worse,
}

/** "Why ›" and "Open plan ›": text links with a 44 pt target each, the
 *  chevron an icon rather than a glyph (App Fixes, rules 03 and 04). */
const LINK = 'inline-flex min-h-11 items-center gap-0.5 text-[13px] font-medium text-accent-text focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring rounded-md'

/** The chevron that ends a text link. */
function LinkChevron() {
  return <ChevronRight size={14} strokeWidth={2.2} aria-hidden className="shrink-0" />
}

/**
 * The coach read card (design review, Oct 2026): the tab's own read under an
 * eyebrow that names its period and tab, one claim, then "Why →" for the case
 * behind it and "Open plan →". The sheet leads with the same claim and lists
 * its evidence worse first; the plan is generated by the coach, so its button
 * only opens it - nothing here implies editing it.
 */
export function CoachRead({ read, eyebrow }: { read: TabRead; eyebrow: string }) {
  const s = t.analytics.cards.coachRead
  const [open, setOpen] = useState(false)
  return (
    <>
      <section data-testid="coach-read" data-tone={read.tone} className="flex flex-col gap-1 rounded-2xl border border-border bg-card px-5 pb-0.5 pt-4">
        <VerdictEyebrow tone={read.tone}>{eyebrow}</VerdictEyebrow>
        <p className="text-[15px] font-semibold leading-snug text-foreground text-pretty" data-testid="coach-read-headline">
          {read.headline}
        </p>
        {read.note && (
          <p className="text-[13px] leading-snug text-[var(--text-2)] text-pretty" data-testid="coach-read-note">
            {read.note}
          </p>
        )}
        <div className="flex items-center gap-5">
          {read.rows.length > 0 && (
            <button type="button" onClick={() => setOpen(true)} aria-haspopup="dialog" className={LINK} data-testid="coach-read-why">
              {s.why}
              <LinkChevron />
            </button>
          )}
          <Link href="/plan" className={LINK} data-testid="coach-open-plan">
            {s.openPlan}
            <LinkChevron />
          </Link>
        </div>
      </section>
      {open && <WhySheet read={read} eyebrow={eyebrow} onClose={() => setOpen(false)} />}
    </>
  )
}

/** "Load 456, under the 462–750 safe range.": the lead, up to the first comma, in bold. */
export function leadSplit(text: string): [string, string] {
  const i = text.indexOf(', ')
  return i > 0 && i < 40 ? [text.slice(0, i), text.slice(i)] : ['', text]
}

/**
 * The case behind the read (App Fixes 1b): a bottom sheet with a grab
 * handle, the eyebrow and claim, one row per piece of evidence with its lead
 * number bold, then "Open plan" beside "Close".
 */
function WhySheet({ read, eyebrow, onClose }: { read: TabRead; eyebrow: string; onClose: () => void }) {
  const s = t.analytics.cards.coachRead
  const trapRef = useFocusTrap<HTMLDivElement>()
  const titleId = useId()
  useScrollLock()
  useEffect(() => {
    const handler = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose()
    }
    document.addEventListener('keydown', handler)
    return () => document.removeEventListener('keydown', handler)
  }, [onClose])

  return createPortal(
    <div className="fixed inset-x-0 bottom-0 top-[var(--safe-top)] z-50 flex items-end justify-center" style={{ touchAction: 'none' }}>
      <div className="absolute inset-0 animate-fade-in bg-black/55" onClick={onClose} aria-hidden />
      <div
        ref={trapRef}
        role="dialog"
        aria-modal="true"
        aria-labelledby={titleId}
        data-testid="why-sheet"
        className="relative flex max-h-[85dvh] w-full max-w-[520px] animate-fade-up flex-col gap-3.5 overflow-y-auto overscroll-contain rounded-t-[28px] border-t border-[var(--line-2)] bg-[var(--surface-sheet,var(--card))] px-5 pt-2.5 pb-[calc(env(safe-area-inset-bottom)+20px)] shadow-[var(--shadow-modal)]"
      >
        <span aria-hidden className="h-1 w-10 self-center rounded-full bg-[var(--rest-bar)]" />
        <VerdictEyebrow tone={read.tone} className="[&>span:first-child]:hidden">{eyebrow}</VerdictEyebrow>
        <h2 id={titleId} className="text-xl font-semibold leading-[1.25] tracking-[-0.01em] text-foreground text-pretty">
          {read.headline}
        </h2>
        <ul className="flex flex-col">
          {read.rows.map((row, i) => {
            const direction = row.direction ?? TREND_DIRECTION[row.trend]
            const Icon = DIRECTION_ICON[direction]
            const [lead, rest] = leadSplit(row.text)
            return (
              <li
                key={i}
                className="grid grid-cols-[28px_minmax(0,1fr)] gap-2.5 border-t border-border py-3 text-sm leading-[1.4] text-[var(--text-2)]"
                data-trend={row.trend}
                data-direction={direction}
              >
                <Icon size={16} strokeWidth={2} className="mt-0.5" style={{ color: TREND_COLOR[row.trend] }} aria-hidden />
                <span>
                  {lead && <b className="font-semibold text-foreground">{lead}</b>}
                  {rest}
                </span>
              </li>
            )
          })}
        </ul>
        <div className="flex gap-2.5">
          <Link
            href="/plan"
            className="flex flex-1 items-center justify-center rounded-[14px] bg-accent py-3.5 text-[15px] font-semibold text-accent-foreground active:opacity-80"
            data-testid="coach-open-plan-button"
          >
            {s.openPlanButton}
          </Link>
          <button type="button" onClick={onClose} className="rounded-[14px] bg-[var(--border)] px-5 py-3.5 text-[15px] font-medium text-foreground active:opacity-80">
            {t.analytics.cards.close}
          </button>
        </div>
      </div>
    </div>,
    document.body,
  )
}
