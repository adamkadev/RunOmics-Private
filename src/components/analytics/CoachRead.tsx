'use client'

import { useId, useState } from 'react'
import Link from 'next/link'
import { ArrowDownRight, ArrowRight, ArrowUpRight, ChevronRight } from 'lucide-react'
import { DELTA_TONE_COLOR } from '@/lib/deltaTone'
import { VerdictEyebrow } from '@/components/ui/Verdict'
import { t } from '@/i18n'
import { Button, ButtonLink } from '@/components/ui/Button'
import { Sheet } from '@/components/ui/Sheet'
import type { Direction, TabRead } from './coachReadTabs'
import type { Trend } from './analyticsView'

/**
 * The arrow follows the number and the colour says what it means: fatigue down 23 is a drop drawn in mint. A row
 * with no number of its own keeps the meaning's arrow.
 */
const DIRECTION_ICON: Record<Direction, typeof ArrowRight> = {
  up: ArrowUpRight,
  level: ArrowRight,
  down: ArrowDownRight,
}

const TREND_DIRECTION: Record<Trend, Direction> = { improving: 'up', flat: 'level', declining: 'down' }

const TREND_COLOR: Record<Trend, string> = {
  improving: DELTA_TONE_COLOR.good,
  flat: DELTA_TONE_COLOR.flat,
  declining: DELTA_TONE_COLOR.worse,
}

const LINK = 'inline-flex min-h-11 items-center gap-0.5 text-[13px] font-medium text-accent-text focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring rounded-md'

function LinkChevron() {
  return <ChevronRight size={14} strokeWidth={2.2} aria-hidden className="shrink-0" />
}

/** The plan is generated by the coach, so its button only opens it: nothing here may imply editing it. */
export function CoachRead({ read, eyebrow }: { read: TabRead; eyebrow: string }) {
  const s = t.analytics.cards.coachRead
  const [open, setOpen] = useState(false)
  return (
    <>
      <section data-testid="coach-read" data-tone={read.tone} className="flex flex-col gap-1 content-card rounded-[24px] bg-card shadow-[var(--card-edge)] px-4 pb-0.5 pt-4">
        <VerdictEyebrow tone={read.tone}>{eyebrow}</VerdictEyebrow>
        <p className="text-[15px] font-semibold leading-snug text-foreground text-pretty" data-testid="coach-read-headline">
          {read.headline}
        </p>
        {read.note && (
          <p className="text-[13px] leading-snug text-[var(--text-2)] text-pretty" data-testid="coach-read-note">
            {read.note}
          </p>
        )}
        <div className="flex items-center gap-5">
          {read.rows.length > 0 && (
            <button type="button" onClick={() => setOpen(true)} aria-haspopup="dialog" className={LINK} data-testid="coach-read-why">
              {s.why}
              <LinkChevron />
            </button>
          )}
          <Link href="/plan" className={LINK} data-testid="coach-open-plan">
            {s.openPlan}
            <LinkChevron />
          </Link>
        </div>
      </section>
      {open && <WhySheet read={read} eyebrow={eyebrow} onClose={() => setOpen(false)} />}
    </>
  )
}

/** "Load 456, under the 462–750 safe range.": the lead, up to the first comma, in bold. */
export function leadSplit(text: string): [string, string] {
  const i = text.indexOf(', ')
  return i > 0 && i < 40 ? [text.slice(0, i), text.slice(i)] : ['', text]
}

function WhySheet({ read, eyebrow, onClose }: { read: TabRead; eyebrow: string; onClose: () => void }) {
  const s = t.analytics.cards.coachRead
  const titleId = useId()

  return (
    <Sheet
      onClose={onClose}
      titleId={titleId}
      showClose={false}
      testId="why-sheet"
      bodyClassName="flex flex-col gap-3.5"
      footer={(close) => (
        <div className="flex gap-2.5">
          <ButtonLink href="/plan" size="lg" className="flex-1" data-testid="coach-open-plan-button">
            {s.openPlanButton}
          </ButtonLink>
          <Button size="lg" variant="secondary" onClick={close}>
            {t.analytics.cards.close}
          </Button>
        </div>
      )}
    >
      <VerdictEyebrow tone={read.tone} className="[&>span:first-child]:hidden">{eyebrow}</VerdictEyebrow>
      <h2 id={titleId} className="text-title-3 text-foreground text-pretty">
        {read.headline}
      </h2>
      <ul className="flex flex-col">
        {read.rows.map((row, i) => {
          const direction = row.direction ?? TREND_DIRECTION[row.trend]
          const Icon = DIRECTION_ICON[direction]
          const [lead, rest] = leadSplit(row.text)
          return (
            <li
              key={i}
              className="grid grid-cols-[28px_minmax(0,1fr)] gap-2.5 border-t-[0.5px] border-[var(--row-separator)] py-3 text-[15px] leading-5 text-[var(--text-2)]"
              data-trend={row.trend}
              data-direction={direction}
            >
              <Icon size={16} strokeWidth={2} className="mt-0.5" style={{ color: TREND_COLOR[row.trend] }} aria-hidden />
              <span>
                {lead && <b className="font-semibold text-foreground">{lead}</b>}
                {rest}
              </span>
            </li>
          )
        })}
      </ul>
    </Sheet>
  )
}
