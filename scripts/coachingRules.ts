import fs from 'fs'
import path from 'path'

export const RULES_PATH = path.join('.claude', 'skills', 'coaching-plan', 'rules.md')
export const GENERATED_PATH = path.join('src', 'infrastructure', 'ai', 'coachingRules.generated.ts')

/** Its bullets also go out on their own: a change to the live plan names its sessions by the same rules. */
export const NAMING_SECTION = 'Naming the workouts'

/** A change to the live plan reads the same notes, check-ins and return state a new block does. */
export const ADAPTATION_SECTIONS = ['What the athlete wrote', 'Returning to running']

function sectionLines(markdown: string, heading: string): string[] {
  const lines = markdown.split('\n')
  const start = lines.findIndex((line) => line.trim() === `## ${heading}`)
  if (start === -1) throw new Error(`No "## ${heading}" section in ${RULES_PATH}`)
  const end = lines.findIndex((line, index) => index > start && line.startsWith('## '))
  return lines.slice(start + 1, end === -1 ? undefined : end)
}

/** The bullets go out as one paragraph in document order; headings and prose around them never reach the model. */
export function rulesFromMarkdown(markdown: string, section?: string): string {
  const lines = section ? sectionLines(markdown, section) : markdown.split('\n')
  const bullets = lines.filter((line) => line.startsWith('- ')).map((line) => line.slice(2).trim())
  if (bullets.length === 0) throw new Error(`No rules found in ${RULES_PATH}${section ? ` under "${section}"` : ''}`)
  return bullets.join(' ')
}

export function generatedSource(instruction: string, naming: string, reading: string): string {
  return [
    `// Generated from ${RULES_PATH.split(path.sep).join('/')} by scripts/generate-coaching-rules.ts.`,
    '// Edit the Markdown and rerun `npm run build:coaching-rules`; do not edit this file.',
    '',
    `export const BOOTSTRAP_SYSTEM_INSTRUCTION = ${JSON.stringify(instruction)}`,
    '',
    `// "${NAMING_SECTION}" alone, for a change to the live plan.`,
    `export const WORKOUT_NAMING_INSTRUCTION = ${JSON.stringify(naming)}`,
    '',
    `// ${ADAPTATION_SECTIONS.map((section) => `"${section}"`).join(' and ')}, for a change to the live plan.`,
    `export const ADAPTATION_READING_INSTRUCTION = ${JSON.stringify(reading)}`,
    '',
  ].join('\n')
}

export function adaptationRules(markdown: string): string {
  return ADAPTATION_SECTIONS.map((section) => rulesFromMarkdown(markdown, section)).join(' ')
}

export function expectedGenerated(root = process.cwd()): string {
  const markdown = fs.readFileSync(path.join(root, RULES_PATH), 'utf-8')
  return generatedSource(rulesFromMarkdown(markdown), rulesFromMarkdown(markdown, NAMING_SECTION), adaptationRules(markdown))
}
