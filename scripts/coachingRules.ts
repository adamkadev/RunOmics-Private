import fs from 'fs'
import path from 'path'

export const RULES_PATH = path.join('.claude', 'skills', 'coaching-plan', 'rules.md')
export const GENERATED_PATH = path.join('src', 'infrastructure', 'ai', 'coachingRules.generated.ts')

/**
 * Each bullet is one instruction and they are sent as one paragraph, so document
 * order is the order the planner reads them in. Headings and prose around them
 * are for the human editing the file and never reach the model.
 */
export function rulesFromMarkdown(markdown: string): string {
  const bullets = markdown.split('\n').filter((line) => line.startsWith('- ')).map((line) => line.slice(2).trim())
  if (bullets.length === 0) throw new Error(`No rules found in ${RULES_PATH}`)
  return bullets.join(' ')
}

export function generatedSource(instruction: string): string {
  return [
    `// Generated from ${RULES_PATH.split(path.sep).join('/')} by scripts/generate-coaching-rules.ts.`,
    '// Edit the Markdown and rerun `npm run build:coaching-rules`; do not edit this file.',
    '',
    `export const BOOTSTRAP_SYSTEM_INSTRUCTION = ${JSON.stringify(instruction)}`,
    '',
  ].join('\n')
}

export function expectedGenerated(root = process.cwd()): string {
  return generatedSource(rulesFromMarkdown(fs.readFileSync(path.join(root, RULES_PATH), 'utf-8')))
}
