import sharp from 'sharp'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { loadLibModules } from './loadPalette.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'public/icons/splash')

const { SURFACES } = await loadLibModules('themeTokens', ['palette', 'accentScale', 'themeTokens'])
const { CURATED_ACCENTS, DEFAULT_ACCENT } = await loadLibModules('accent', ['accentScale', 'accent'])
const BG = SURFACES.dark.background
const LOGO_COLOR = CURATED_ACCENTS.find((a) => a.id === DEFAULT_ACCENT).dark.acc

const DEVICES = [
  { name: 'iphone-16-pro-max', w: 440, h: 956, r: 3 },
  { name: 'iphone-16-pro', w: 402, h: 874, r: 3 },
  { name: 'iphone-16-plus', w: 430, h: 932, r: 3 },
  { name: 'iphone-16', w: 393, h: 852, r: 3 },
  { name: 'iphone-14-plus', w: 428, h: 926, r: 3 },
  { name: 'iphone-14-pro', w: 393, h: 852, r: 3 },
  { name: 'iphone-13', w: 390, h: 844, r: 3 },
  { name: 'iphone-13-mini', w: 375, h: 812, r: 3 },
  { name: 'iphone-11-pro-max', w: 414, h: 896, r: 3 },
  { name: 'iphone-11', w: 414, h: 896, r: 2 },
  { name: 'iphone-8-plus', w: 414, h: 736, r: 3 },
  { name: 'iphone-8', w: 375, h: 667, r: 2 },
  { name: 'iphone-se', w: 320, h: 568, r: 2 },
  { name: 'ipad-pro-12', w: 1024, h: 1366, r: 2 },
  { name: 'ipad-pro-11', w: 834, h: 1194, r: 2 },
  { name: 'ipad-air-10-9', w: 820, h: 1180, r: 2 },
  { name: 'ipad-10-2', w: 810, h: 1080, r: 2 },
  { name: 'ipad-9-7', w: 768, h: 1024, r: 2 },
]

const rawSvg = readFileSync(join(root, 'public/icons/mark.svg'), 'utf8')
const coloredSvg = rawSvg.replaceAll('currentColor', LOGO_COLOR)

const seen = new Set()

async function render(pxW, pxH, file) {
  const logoSize = Math.round(Math.min(pxW, pxH) * 0.28)
  const logo = await sharp(Buffer.from(coloredSvg), { density: 384 })
    .resize(logoSize, logoSize, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png()
    .toBuffer()
  await sharp({ create: { width: pxW, height: pxH, channels: 4, background: BG } })
    .composite([{ input: logo, gravity: 'center' }])
    .png()
    .toFile(join(outDir, file))
}

mkdirSync(outDir, { recursive: true })
const entries = []

for (const d of DEVICES) {
  for (const orientation of ['portrait', 'landscape']) {
    const portrait = orientation === 'portrait'
    const cssW = portrait ? d.w : d.h
    const cssH = portrait ? d.h : d.w
    const pxW = cssW * d.r
    const pxH = cssH * d.r
    const key = `${pxW}x${pxH}`
    if (seen.has(key)) continue
    seen.add(key)

    const file = `${d.name}-${orientation}.png`
    await render(pxW, pxH, file)
    const media =
      `(device-width: ${d.w}px) and (device-height: ${d.h}px) ` +
      `and (-webkit-device-pixel-ratio: ${d.r}) and (orientation: ${orientation})`
    entries.push({ url: `/icons/splash/${file}`, media })
  }
}

const ts =
  `// AUTO-GENERATED by scripts/generate-splash.mjs - do not edit by hand.\n` +
  `export const appleStartupImages = ${JSON.stringify(entries, null, 2)} as const\n`
writeFileSync(join(root, 'src/lib/splashScreens.ts'), ts)

console.log(`Generated ${entries.length} splash screens in public/icons/splash/`)
