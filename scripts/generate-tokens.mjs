import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { ROOT, loadLibModules } from './loadPalette.mjs'

const CSS_PATH = join(ROOT, 'src/app/globals.css')
const START = '/* ─── GENERATED by `npm run tokens` - edit src/lib/themeTokens.ts ─── */'
const END = '/* ─── END GENERATED ─── */'

const { TOKEN_BLOCKS } = await loadLibModules('themeTokens', ['palette', 'oklch', 'accentScale', 'themeTokens'])

const banner = (text) => {
  const line = `/* ─── ${text} `
  return line + '─'.repeat(Math.max(3, 54 - line.length)) + ' */'
}

const chunks = TOKEN_BLOCKS.map(({ selector, comment, tokens }) => {
  const entries = Object.entries(tokens)
  const width = Math.max(...entries.map(([k]) => k.length)) + 1
  const body = entries.map(([k, v]) => `  ${(k + ':').padEnd(width + 1)} ${v};`).join('\n')
  return `${comment ? banner(comment) + '\n' : ''}${selector} {\n${body}\n}`
})

const generated = [START, ...chunks, END].join('\n\n')

const css = readFileSync(CSS_PATH, 'utf8')
const from = css.indexOf(START)
const to = css.indexOf(END)
if (from === -1 || to === -1) {
  throw new Error(`Missing generated markers in ${CSS_PATH}. Expected:\n${START}\n...\n${END}`)
}

writeFileSync(CSS_PATH, css.slice(0, from) + generated + css.slice(to + END.length))
console.log(`✓ globals.css: ${TOKEN_BLOCKS.length} token blocks written`)
